"""Render docs/seeds.md from experiments/seed_registry.json (copied from the postpay repository). Free. Usage: python eval/seed_registry_report.py [--write]
Without --write it prints the page; tests/test_seed_registry.py fails when docs/seeds.md is stale."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import seed_registry as sr  # noqa: E402

OUT = os.path.join(ROOT, "docs", "seeds.md")
ORDER = ("fit", "select", "confirm", "test")


def can_still(pool):
    st, kind = pool["status"], pool["kind"]
    if st == "reserved":
        return "Only a final test of a frozen version, once. Never generated, never used for development."
    if st == "fresh":
        return "One test of a frozen version; nothing else."
    if kind == "test":
        return "Not a clean test any more. A named later version can look at it as a declared second use; otherwise development data."
    if st == "in_use":
        return "A confirm for a hypothesis whose design did not see its results; development data for the rest."
    return "Development data only (fit, select, explore). No clean hold-out for any arm that saw it."


def uses_text(pool):
    out = []
    for role in ORDER:
        arms = []
        for u in pool["uses"]:
            if u["role"] != role:
                continue
            a = u["arm"]
            if u.get("done") is False:
                a += " (not run yet)"
            elif u.get("second_use"):
                a += " (second use)"
            if a not in arms:
                arms.append(a)
        if arms:
            out.append(f"{role}: {', '.join(arms)}")
    return "; ".join(out) if out else "none"


def render(reg=None):
    reg = reg or sr.load()
    v = reg["vocabulary"]
    L = ["# Seed pools: who fitted, selected, confirmed and tested on which seeds", "",
         "[Back to the README](../README.md) · [versions](versioning.md) · [process](process.md)", "",
         "Generated by `python eval/seed_registry_report.py --write` from `experiments/seed_registry.json` (the source of truth; `src/seed_registry.py` reads it, and the run scripts check it before running). A seed number alone means nothing: seed 2001 of data 4.2 and seed 2001 of another data version are different datasets, so every pool is keyed by data version and seed list. Free to read; nothing here runs a model.", "",
         "## Words", ""]
    for k in ("fit", "select", "confirm", "test", "burned", "fresh", "reserved", "in_use"):
        L.append(f"- **{k.replace('_', ' ')}**: {v[k]}.")
    L += ["", "A seed is a hold-out only for one arm and one decision made before its results were read. When a result from a pool informs a later design, the pool is burned for that line. Each new family of hypotheses gets a new confirm pool (making development seeds is free); the final test pool stays untouched until the freeze.", "",
          "## Pools", "",
          "| Pool | Data | Seeds | Status | Roles by arm | What it can still be used for |", "|---|---|---|---|---|---|"]
    for p in reg["pools"]:
        status = p["status"].replace("_", " ") + (f" ({p['status_date']})" if p.get("status_date") else "")
        L.append(f"| {p['id']} | {p['data_version']} | {sr.ranges(p['seeds'])} ({len(p['seeds'])}) | {status} | {uses_text(p)} | {can_still(p)} |")
    L += ["", "## Notes by pool", ""]
    for p in reg["pools"]:
        L.append(f"**{p['id']}** ({p['kind']}). {p['status_note']}.")
        for u in p["uses"]:
            sub = f", seeds {sr.ranges(u['seeds'])}" if u.get("seeds") else ""
            when = u["date"] or "date not recorded"
            flag = ", planned, not run" if u.get("done") is False else (", second use" if u.get("second_use") else "")
            L.append(f"- {u['arm']}, {u['role']}{sub} ({when}{flag}; {u['reference']}): {u['note']}.")
        L.append("")
    if reg.get("arm_aliases"):
        L += ["Arm names: " + ", ".join(f"{a} is {b}" for a, b in reg["arm_aliases"].items()) + ".", ""]
    L += ["Planned uses (not run yet) are declared before the run; a run turns its planned use into a recorded one with `seed_registry.record_use`.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        with open(OUT, "w") as f:
            f.write(text)
        print("wrote", OUT)
    else:
        print(text)
